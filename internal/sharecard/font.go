// glyphs are glyphRows as bits: bit 4 is the leftmost pixel of a row.
var glyphs = func() map[rune][glyphHeight]uint8 {
	out := make(map[rune][glyphHeight]uint8, len(glyphRows))
	for r, rows := range glyphRows {
		var g [glyphHeight]uint8
		for i, row := range strings.Fields(rows) {
			for j, c := range row {
				if c == '#' {
					g[i] |= 1 << (glyphWidth - 1 - j)
				}
			}
		}
		out[r] = g
	}
	return out
}()

