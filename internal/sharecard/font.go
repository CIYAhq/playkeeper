// drawable is s in what the font draws: marks folded away, and anything it
// has no glyph for, such as emoji, left out.
func drawable(s string) string {
	var b strings.Builder
	for _, r := range s {
		if f, ok := folds[r]; ok {
			b.WriteString(f)
			continue
		}
		if _, ok := glyphs[r]; ok {
			b.WriteRune(r)
		}
	}
	return strings.Join(strings.Fields(b.String()), " ")
}
