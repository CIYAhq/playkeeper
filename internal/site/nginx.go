package site

import (
	"fmt"
	"net/url"
	"regexp"
	"slices"
	"strings"
)

// whopPixel is where Whop's ad pixel (Settings.WhopPixel) loads its scripts
// from and sends its events to.
const whopPixel = "https://t.whop.tw"

// nginxInclude is the part of nginx.conf that follows the settings and the
// pages: the Content-Security-Policy, /community, which the live demo links
// to, /start, the pages that play a film, the pages' short addresses and the
// channels' links.
func nginxInclude(s Settings, pages []*Page) []byte {
	return []byte(fmt.Sprintf(`# Generated by cmd/site from internal/site/settings.go and site/pages; do not edit.
# The Content-Security-Policy, and X-Robots-Tag where a page is kept out of
# search engines: a location changes them with set, not add_header, which
# would drop every header this server adds.
set $csp "%s";
set $robots "";
add_header Content-Security-Policy $csp always;
add_header X-Robots-Tag $robots always;

# Where questions go (Settings.Community). The live demo links here, so it
# follows the setting without a rebuild of the dashboard.
location = /community {
    return 302 %s;
}

# Where the Meta ads land. Its policy alone lets Whop's ad pixel in
# (Settings.WhopPixel), with the worker it starts from a blob, and the film.
# Kept out of search engines, and answered with no redirect, so the pixel
# still finds the ad's IDs in the query string.
location = /start {
    set $csp "%s";
    set $robots noindex;
    expires -1;
    try_files /start.html =404;
}

# Pages that play a film (a page's film setting): their policy lets the
# site's own video in too.
%s
# Short addresses for posts and videos (a page's short setting): the page,
# with the query string, in any case and with or without a trailing slash.
%s
# Channel links (Settings.Channels): the landing page with the channel's UTM
# tags, where it shows the channel's install command.
%s`, contentSecurityPolicy(s, false, false), s.Community.URL, contentSecurityPolicy(s, true, true), filmLocations(s, pages), shortLinks(pages), channelLinks(s.Channels)))
}

// contentSecurityPolicy is the site's policy; with film, a page's that plays
// a film of the site's own, and with pixel too, /start's.
func contentSecurityPolicy(s Settings, film, pixel bool) string {
	ad := ""
	if pixel && s.WhopPixel != "" {
		ad = whopPixel
	}
	d := []string{
		"default-src 'none'",
		"script-src " + sources("'self'", origin(s.Analytics.Script), ad),
		"style-src 'self'",
		"img-src 'self'",
	}
	if film {
		d = append(d, "media-src 'self'")
	}
	if ad != "" {
		d = append(d, "worker-src blob:")
	}
	return strings.Join(append(d,
		// The header's star count, once there are enough stars to show, and
		// this site, where audits like Lighthouse read robots.txt from the
		// page. img-src already lets a page ask this site for things. The
		// stats service takes copies of the install command.
		"connect-src "+sources("'self'", "https://api.github.com", origin(s.Analytics.Collector), origin(s.Stats), ad),
		"base-uri 'none'",
		"form-action 'none'",
		"frame-ancestors 'none'",
	), "; ")
}

// films are the pages that play a film in a location of their own, by path:
// all but /start, whose location lets its film in already.
func films(pages []*Page) []*Page {
	var out []*Page
	for _, p := range byAddress(pages) {
		if p.Film && p.Path != "/start" {
			out = append(out, p)
		}
	}
	return out
}

// filmLocations is the location of each page that plays a film: the page, as
// nginx.conf's location / answers it, with the film's policy.
func filmLocations(s Settings, pages []*Page) string {
	var b strings.Builder
	for _, p := range films(pages) {
		fmt.Fprintf(&b, "location = %s {\n    set $csp \"%s\";\n    expires -1;\n    try_files /%s =404;\n}\n", p.Path, contentSecurityPolicy(s, true, false), p.outFile())
	}
	return b.String()
}

// reShort is a page's short address: one word under /, which nginx matches in
// any case.
var reShort = regexp.MustCompile(`^/[a-z0-9]+(?:-[a-z0-9]+)*$`)

// answered are the addresses site/nginx.conf and this include answer
// themselves, which no short address can take.
var answered = []string{"/install", "/demo", "/healthz", "/index", "/404", "/assets", "/community", "/go"}

// checkShort checks the pages' short addresses: none is a page, another
// page's short address, or an address nginx answers itself.
func checkShort(pages []*Page) error {
	taken := map[string]string{}
	for _, p := range pages {
		taken[strings.ToLower(p.Path)] = "the page " + p.Path
	}
	for _, a := range answered {
		taken[a] = "nginx's own " + a
	}
	for _, p := range byAddress(pages) {
		if p.Short == "" {
			continue
		}
		if what, ok := taken[p.Short]; ok {
			return fmt.Errorf("%s: its short address %s is %s", p.Path, p.Short, what)
		}
		taken[p.Short] = p.Path + "'s short address"
	}
	return nil
}

// shortLinks is nginx's short address for each page that has one: a 302 to
// the page that keeps the query string, so a post's UTM tags reach it.
func shortLinks(pages []*Page) string {
	var b strings.Builder
	for _, p := range byAddress(pages) {
		if p.Short != "" {
			fmt.Fprintf(&b, "location ~* ^%s/?$ {\n    return 302 %s$is_args$args;\n}\n", p.Short, p.Path)
		}
	}
	return b.String()
}

// byAddress is the pages in the order of their paths, for an include that
// doesn't change from one build to the next.
func byAddress(pages []*Page) []*Page {
	out := slices.Clone(pages)
	slices.SortFunc(out, func(a, b *Page) int { return strings.Compare(a.Path, b.Path) })
	return out
}

// sources is a directive's sources, leaving out empty ones.
func sources(list ...string) string {
	return strings.Join(slices.DeleteFunc(list, func(s string) bool { return s == "" }), " ")
}

// origin is an address's scheme and host, as a Content-Security-Policy source;
// empty for an empty address.
func origin(addr string) string {
	u, err := url.Parse(addr)
	if err != nil || u.Host == "" {
		return ""
	}
	return u.Scheme + "://" + u.Host
}
